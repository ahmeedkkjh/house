exception when duplicate_object then null; end $$;
do $$ begin
  create policy "authenticated users can manage expenses" on public.expenses for all to authenticated using (true) with check (true);
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "authenticated users can manage purchases" on public.purchases for all to authenticated using (true) with check (true);
exception when duplicate_object then null; end $$;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.products, public.orders, public.order_items, public.expenses, public.purchases to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- إنشاء الفاتورة وتفاصيلها في معاملة واحدة. لا يمكن أن تُحفظ الفاتورة وحدها إذا فشلت التفاصيل.
create or replace function public.create_restaurant_order(
  p_customer_name text,
  p_payment_method text,
  p_discount numeric,
  p_items jsonb
) returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_order_id uuid;
  v_subtotal numeric(12,2) := 0;
  v_discount numeric(12,2) := greatest(coalesce(p_discount,0),0);
  v_total numeric(12,2);
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_price numeric(12,2);
  v_cost numeric(12,2);
  v_name text;
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول أولاً'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'الفاتورة يجب أن تحتوي على صنف واحد على الأقل'; end if;
  if p_payment_method not in ('cash','card','wallet','other') then raise exception 'طريقة الدفع غير صحيحة'; end if;
  -- التحقق من الأصناف والكميات وحساب الإجمالي من أسعار قاعدة البيانات، لا من المتصفح.
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    if v_qty < 1 then raise exception 'الكمية يجب أن تكون 1 أو أكثر'; end if;
    select * into v_product from public.products where id=(v_item->>'product_id')::uuid and active=true;
    if not found then raise exception 'أحد الأصناف غير موجود أو موقوف'; end if;
    v_subtotal := v_subtotal + (v_product.price * v_qty);
  end loop;
  if v_discount > v_subtotal then raise exception 'الخصم أكبر من الإجمالي'; end if;
  v_total := v_subtotal - v_discount;
  insert into public.orders(customer_name,payment_method,subtotal,discount,total,created_by)
  values (coalesce(nullif(trim(p_customer_name),''),'عميل نقدي'),p_payment_method,v_subtotal,v_discount,v_total,auth.uid()) returning id into v_order_id;
  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    select * into v_product from public.products where id=(v_item->>'product_id')::uuid and active=true;
    insert into public.order_items(order_id,product_id,product_name,quantity,unit_price,unit_cost)
    values(v_order_id,v_product.id,v_product.name,v_qty,v_product.price,v_product.cost);
  end loop;
  return v_order_id;
end; $$;
grant execute on function public.create_restaurant_order(text,text,numeric,jsonb) to authenticated;
