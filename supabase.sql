create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  price numeric(12,2) not null check (price > 0),
  cost numeric(12,2) not null default 0 check (cost >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  invoice_no bigint generated by default as identity unique,
  customer_name text not null default 'عميل نقدي',
  payment_method text not null default 'cash' check (payment_method in ('cash','card','wallet','other')),
  subtotal numeric(12,2) not null check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null check (total >= 0),
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  unit_cost numeric(12,2) not null default 0 check (unit_cost >= 0),
  line_total numeric(12,2) generated always as (quantity * unit_price) stored
);
create table if not exists public.expenses (
  id uuid primary key default gen_random_uuid(), title text not null,
  amount numeric(12,2) not null check (amount > 0),
  expense_date date not null default current_date, notes text,
  created_at timestamptz not null default now(), created_by uuid references auth.users(id)
);
create table if not exists public.purchases (
  id uuid primary key default gen_random_uuid(), title text not null,
  amount numeric(12,2) not null check (amount > 0),
  purchase_date date not null default current_date, notes text,
  created_at timestamptz not null default now(), created_by uuid references auth.users(id)
);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.expenses enable row level security;
alter table public.purchases enable row level security;

do $$ begin
  create policy "authenticated users can manage products" on public.products for all to authenticated using (true) with check (true);
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "authenticated users can manage orders" on public.orders for all to authenticated using (true) with check (true);
